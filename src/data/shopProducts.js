export function getProductById(productId) {
  return shopProducts.find((p) => p.id === productId) || null;
}

export function getProductsByCategory(categoryKey) {
  if (categoryKey === 'all') return shopProducts;
  return shopProducts.filter((p) => p.category === categoryKey);
}

export function searchProducts(query) {
  const q = query.trim().toLowerCase();
  if (!q) return shopProducts;
  return shopProducts.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.desc.toLowerCase().includes(q) ||
      p.categoryLabel.toLowerCase().includes(q) ||
      p.tags?.some((t) => t.toLowerCase().includes(q))
  );
}
